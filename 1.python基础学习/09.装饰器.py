'''装饰器
简单来说，装饰器 = 给函数"穿衣服"，不改函数本身，但能给它加功能。

1.直观感受装饰器用途
假设你有 10 个函数，每个都要在执行前后打印日志，
问题：日志代码和业务代码混在一起，乱。
**解决思路：把"打印开始/结束"这个功能单独拿出来，像贴纸一样贴到任意函数上。
这就是装饰器。

2.加上参数，支持任意函数
上面的 包裹() 只能调用无参函数。真实场景要用 *args, **kwargs

a. *args：无标签包裹
一个星 * 的意思是：“所有没贴标签、只按顺序扔进来的东西，统统打包进一个元组(1, 2, 3)，
接收位置参数：func(1, 2, 3)

b. **kwargs：贴标签包裹
两个星 ** 的意思是：“所有贴了标签（关键词=值）的东西，统统打包进一个字典（像一本通讯录，左边名字，右边内容）{'a':1, 'b':2}。
接收关键字参数：func(a=1, b=2)

c. 对比表
                位置参数	              关键字参数
调用时	      func(1, 2, 3)	         func(a=1, b=2, c=3)
本质	             按顺序对应	              按名字对应
打包后	      元组 (1, 2, 3)	         字典 {'a':1, 'b':2, 'c':3}
* 对应位置参数 → 打包成元组（有序，无名字）
** 对应关键字参数 → 打包成字典（无序，有名字）

d. 混合模式：既能接收位置又能接收关键字参数
def 万能函数(*args, **kwargs):
    print(f"无标签参数：{args}")
    print(f"有标签参数：{kwargs}")

e. 解包和打包
场景	            写法	                          作用
定义函数时	def func(*args)	        把传入的多个参数打包成元组
调用函数时	func(*元组)	            把元组解包成多个参数
定义函数时	def func(**kwargs)	    把传入的关键字参数打包成字典
调用函数时	func(**字典)          	把字典解包成关键字参数

#3.装饰器本身带参数（三层嵌套）——装饰器也要吃配置？
有时候你希望装饰器自己能接受参数，比如：“我要加日志，但前缀可以自定义”。
比如 @log(prefix="INFO")。


'''
#1.假设你有 10 个函数，每个都要在执行前后打印日志：
def func1():
    print("开始")
    # 做事情
    print("结束")

def func2():
    print("开始")
    # 做事情
    print("结束")
# ... 重复10次，烦死了
# 这就是一个装饰器（模板）
def 我的装饰器(func):          # ① 接收一个函数
    def 包裹():                 # ② 内部定义一个新函数
        print("—— 开始 ——")
        func()                  # ③ 调用原函数
        print("—— 结束 ——")
    return 包裹                 # ④ 返回新函数

# 使用：用 @ 语法"贴上去"
@我的装饰器
def 说句话():
    print("你好啊")

说句话()
#@我的装饰器 等价于 说句话 = 我的装饰器(说句话)

#2.加上参数，支持任意函数
def 日志装饰器(func):
    def 包裹(*args, **kwargs):     # ⭐ 万能参数，啥函数都能接
        print(f"调用了 {func.__name__}")
        结果 = func(*args, **kwargs)   # 执行原函数，拿到返回值
        print(f"执行完毕，返回值是 {结果}")
        return 结果                    # ⭐ 别忘了返回！
    return 包裹

@日志装饰器
def 加法(a, b):
    return a + b

@日志装饰器
def 打招呼(名字, 语气="开心"):
    return f"{名字}今天很{语气}"

print(加法(3, 5))
print(打招呼("小明", 语气="累"))

#3.比如你想控制日志级别：
def 日志级别(级别="INFO"):           #装饰器传参，最外层
    def 装饰器(func):               #装饰器真部
        def 包装(*args,**kwargs):   #装饰器的包装函数
            print(f'[{级别}]正在执行{func.__name__}')
            return func(*args,**kwargs)
        return 包装
    return 装饰器

@日志级别(级别='危险')
def 危险操作():
    print('正在拆弹')

危险操作()

'''知识点1.带参装饰器 = 三层函数嵌套
层级	                           作用
第1层 日志(级别)	           接收装饰器的参数
第2层 真正的装饰器(func)	   接收被装饰的函数
第3层 包裹()	               执行时真正运行的代码

'''

'''知识点2 函数和函数()区别
写法	                 返回什么	        什么时候用
return 包装	     返回函数本身（对象）	✅ 正确，99%的情况
return 包装()	 返回函数的执行结果	❌ 几乎永远不要这样写
定义函数时，不加括号；调用函数时，才加括号。

'''

